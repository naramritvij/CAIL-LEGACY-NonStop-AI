"""Fictional contributor examples for the Knowledge Tree walkthrough."""
from dataclasses import dataclass
from datetime import date, timedelta


@dataclass(frozen=True)
class Sample:
    title: str
    topic: str
    problem: str
    decision: str
    reasoning: str
    applies: str
    outcome: str
    proposed: bool = False

    def content(self, index):
        used_on = date(2026, 10, 29) - timedelta(days=index % 26)
        return '\n\n'.join((
            f'Fictional Knowledge Tree sample · SIM-KT-{index + 1:02d}',
            f'Problem\n{self.problem}',
            f'{"Proposed solution" if self.proposed else "Decision used"}\n{self.decision}',
            f'Why\n{self.reasoning}',
            f'{"Recorded on" if self.proposed else "Used on"}\n{used_on:%b %d, %Y} · simulated overnight shift',
            f'When to reuse\n{self.applies}',
            f'{"Verification status" if self.proposed else "Observed outcome"}\n{self.outcome}',
        ))


