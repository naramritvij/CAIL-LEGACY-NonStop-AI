function series(startIso: string, count: number, stepMinutes: number, valueAt: (i: number) => number): MetricSample[] {
  const start = Date.parse(startIso)
  return Array.from({ length: count }, (_, i) => ({
    t: new Date(start + i * stepMinutes * 60_000).toISOString(),
    value: Math.round(valueAt(i) * 10) / 10,
  }))
}

